#Simulate a WhatsApp group chat: create a 2D NumPy array where each row is a user and each column is the number of messages sent per day
#for a week. Use np.insert() to add a new user (row) with their message counts, then use np.delete()
#to remove the user who sent the least messages overall.

# Rows = users
# Columns = messages sent from Monday to Sunday
chat = np.array([
    [10, 12, 8, 15, 9, 11, 13],   # User 1
    [5, 7, 6, 8, 4, 5, 6],        # User 2
    [20, 18, 22, 15, 19, 21, 17],  # User 3
    [3, 4, 2, 5, 3, 2, 4]         # User 4
])

print("Original chat:")
print(chat)

# New user's weekly messages
new_user = [8, 9, 7, 10, 6, 8, 9]

# Insert new user as a new row
chat = np.insert(chat, 4, new_user, axis=0)

print("\nAfter adding new user:")
print(chat)

# Find the user with the least total messages
total_messages = np.sum(chat, axis=1)
least_user = np.argmin(total_messages)

print("\nTotal messages of each user:")
print(total_messages)

print("User removed:", least_user + 1)

# Delete the user with the least messages
chat = np.delete(chat, least_user, axis=0)

print("\nAfter removing least active user:")
print(chat)

