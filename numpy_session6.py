import numpy as np

#Create a NumPy array called prices with the following values: [199, 299, 399, 499, 599].
#Use basic indexing to print the first and last price.

prices = np.array([199, 299, 399, 499, 599])

print("First price:", prices[0])
print("Last price:", prices[-1])

#Given a 2D NumPy array representing cricket scores for 3 players across 5 matches, use slicing to extract the scores of
#all players for matches 2 to 4 (index 1 to 3).

scores = np.array([
    [45, 60, 72, 80, 55],
    [50, 65, 70, 85, 60],
    [40, 55, 68, 75, 50]
])

result = scores[:, 1:4]

print(result)

#You have a NumPy array called ratings = np.array([4.5, 3.8, 4.2, 2.9, 5.0, 3.5]).
#Use negative indexing to print the last three ratings.

