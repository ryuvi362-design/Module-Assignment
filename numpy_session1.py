#Write a function compare_addition_speed() that adds 5 to every element in both a Python list and a NumPy array of 10,000 integers,
#and prints the time taken for each.<br><br><em><strong>Hint:</strong> Use the time module to measure execution time.</em>

import numpy as np
import time

def compare_addition_speed():
    my_list = list(range(1, 10001))
    my_array = np.arange(1, 10001)

    start = time.time()

    for i in range(len(my_list)):
        my_list[i] = my_list[i] + 5

    print("List time:", time.time() - start)

    start = time.time()

    my_array = my_array + 5

    print("Array time:", time.time() - start)

compare_addition_speed()

