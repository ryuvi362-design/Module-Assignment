#Build a NumPy array representing the prices of 12 food items from a Zomato order, then use ravel(), flatten(), and resize() to create different shaped versions of the data and print each result.<br><br><em><strong>Constraint:</strong> Show the
#difference between ravel() and flatten() in your code comments.</em>

prices = np.array([[100, 200, 150, 250],
                   [300, 120, 180, 220],
                   [90, 160, 280, 140]])

print("Original:")
print(prices)
# ravel() changes 2D to 1D
# ravel() usually gives a view
print("Ravel:")
print(prices.ravel())
# flatten() changes 2D to 1D
# flatten() gives a copy
print("Flatten:")
print(prices.flatten())

# resize() changes the original shape
prices.resize(4, 3)

print("Resize:")
print(prices)

